    """Return the inline sprite: every doodle, defined once per page."""
    parts = [SPRITE_OPEN]

    for name, body in ICONS.items():
        parts.append(
            '<symbol id="%s" viewBox="0 0 64 64"><g fill="none" stroke="currentColor" '
            'stroke-width="%s" stroke-linecap="round" stroke-linejoin="round">%s</g></symbol>'
            % (name, STROKE, body.strip())
        )

    parts.append(
        '<symbol id="i-scene" viewBox="0 0 320 190"><g fill="none" stroke="currentColor" '
        'stroke-width="%s" stroke-linecap="round" stroke-linejoin="round">%s%s</g></symbol>'
        % (SCENE_STROKE, SCENE.strip(), SCENE_EXTRA.strip())
    )

    parts.append(SPRITE_CLOSE)
    return "\n".join(parts)
